function score(choices) {
  if (!Array.isArray(choices) || choices.length !== questions.length) {
    throw new Error("need " + questions.length + " answers");
  }
  const totals = {};
  keys.forEach((key) => { totals[key] = 0; });
  choices.forEach((optionIndex, questionIndex) => {
    const option = questions[questionIndex].options[optionIndex];
    if (!option) throw new Error("bad answer " + questionIndex + " " + optionIndex);
    keys.forEach((key) => { totals[key] += option.weights[key]; });
  });
  const ranked = keys
    .map((key) => ({ key, score: totals[key], city: cities[key] }))
    .sort((a, b) => b.score - a.score || a.city.name.localeCompare(b.city.name, "zh"));
  return { primary: ranked[0], secondary: ranked[1], ranked, choices };
}

function encodeAnswers(choices) {
  const decoded = score(choices).choices;
  return decoded.map((index) => String.fromCharCode(65 + index)).join("");
}

function decodeAnswers(code) {
  const text = String(code || "").trim().toUpperCase();
  const size = questions.length;
  if (!new RegExp("^[A-Z]{" + size + "}$").test(text)) return null;
  const choices = [];
  for (let i = 0; i < size; i += 1) {
    const index = text.charCodeAt(i) - 65;
    if (!questions[i].options[index]) return null;
    choices.push(index);
  }
  return choices;
}

function extractAnswerCode(line) {
  const upper = String(line || "").toUpperCase();
  const size = questions.length;
  const pattern = new RegExp("(?:^|[^A-Z])([A-Z]{" + size + "})(?![A-Z])", "g");
  let match = pattern.exec(upper);
  while (match) {
    const choices = decodeAnswers(match[1]);
    if (choices) return { code: match[1], choices };
    match = pattern.exec(upper);
  }
  return null;
}

function lineFor(key, questionIndex, optionIndex) {
  const cell = notes[key][questionIndex][optionIndex];
  if (!cell || cell[0] === 2) return null;
  const label = questions[questionIndex].options[optionIndex].label;
  const lead = questionIndex === 1 ? "生活费你选了「" + label + "」。" : "你选了「" + label + "」。";
  return { fit: cell[0] === 1, text: lead + cell[1] };
}

function buildAdvice(key, choices, limits) {
  const found = [];
  choices.forEach((optionIndex, questionIndex) => {
    const line = lineFor(key, questionIndex, optionIndex);
    if (line) found.push({ questionIndex, fit: line.fit, text: line.text });
  });
  const childIndex = questions.findIndex((question) => question.q.includes("娃"));
  const sortPoints = (list) => list.sort((a, b) => {
    const rank = (item) => {
      if (item.questionIndex === 1) return 0;
      if (item.questionIndex === childIndex && choices[childIndex] > 0) return 1;
      return 2 + item.questionIndex;
    };
    return rank(a) - rank(b);
  });
  const good = sortPoints(found.filter((item) => item.fit)).slice(0, limits.good).map((item) => item.text);
  const care = sortPoints(found.filter((item) => !item.fit)).slice(0, limits.care).map((item) => item.text);
  if (!good.length) good.push(cities[key].name + "和你这组选择只有部分重叠，适合拿来作比较，不适合当唯一答案。");
  if (!care.length) care.push("这组选择和" + cities[key].name + "大体对齐，租房位置一变，每月花费还会浮动。");
  return { good, care };
}

function replyFromChoices(choices) {
  const result = score(choices);
  const blocks = [
    { item: result.primary, role: "首选", limits: { good: 3, care: 2 } },
    { item: result.secondary, role: "次选", limits: { good: 2, care: 1 } },
  ].map(({ item, role, limits }) => {
    const advice = buildAdvice(item.key, choices, limits);
    return [
      role + " " + item.city.name,
      item.city.persona + item.city.spend + "，一个人，不算房贷。",
      "优点：\n- " + advice.good.join("\n- "),
      "要注意：\n- " + advice.care.join("\n- "),
    ].join("\n");
  });
  return blocks.join("\n");
}

